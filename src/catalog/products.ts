function offer(
  supplierId: string,
  url: string,
  amount: number | null,
  extra: { regularAmount?: number; note?: string; sourceUrl?: string } = {},
): Offer {
  return {
    supplierId,
    url,
    price: {
      amount,
      currency: 'EUR',
      includesVat: true,
      regularAmount: extra.regularAmount,
      note: extra.note,
      sourceUrl: extra.sourceUrl ?? url,
      checkedAt: CHECKED,
    },
    affiliate: { enabled: false, trackingUrl: null },
  };
}

